import { useMigrations } from 'drizzle-orm/expo-sqlite/migrator';
import { Stack } from 'expo-router';
import { StatusBar } from 'expo-status-bar';
import { useEffect, useRef, useState, type ComponentRef } from 'react';
import { ActivityIndicator, View } from 'react-native';
import { SafeAreaProvider } from 'react-native-safe-area-context';
import { AppText, Snackbar, ThemeFade, ThemeSync } from '@/components';
import { db } from '@/db/client';
import { seedIfEmpty, topUpSeed } from '@/db/seed';
import { NotificationSync } from '@/features/notifications/NotificationSync';
import { LockGate } from '@/features/security/LockGate';
import { UpdateSync } from '@/features/updates/UpdateSync';
import { useTheme } from '@/theme';
// Generated by `npm run db:generate` (drizzle-kit). Run it after any schema change.
import migrations from '../../drizzle/migrations';

export default function RootLayout() {
  const { colors, isDark } = useTheme();
  const { success, error } = useMigrations(db, migrations);
  const [ready, setReady] = useState(false);
  const [seedError, setSeedError] = useState<string | null>(null);
  const screenRef = useRef<ComponentRef<typeof View>>(null);

  useEffect(() => {
    if (!success) return;
    try {
      seedIfEmpty(db);
      topUpSeed(db);
      setReady(true);
    } catch (e) {
      setSeedError(e instanceof Error ? e.message : String(e));
    }
  }, [success]);

  const problem = error?.message ?? seedError;
  if (problem || !ready) {
    return (
      <View style={{ flex: 1, alignItems: 'center', justifyContent: 'center', backgroundColor: colors.background, padding: 24 }}>
        <ThemeSync />
        <StatusBar style={isDark ? 'light' : 'dark'} />
        {problem ? <AppText>Database error: {problem}</AppText> : <ActivityIndicator color={colors.text} />}
      </View>
    );
  }

  return (
    <SafeAreaProvider>
      <ThemeSync />
      <NotificationSync />
      <UpdateSync />
      <StatusBar style={isDark ? 'light' : 'dark'} />
      {/* Everything the theme cross-fade snapshots; ThemeFade sits on top of it. */}
      <View ref={screenRef} collapsable={false} style={{ flex: 1, backgroundColor: colors.background }}>
        <Stack screenOptions={{ headerShown: false, contentStyle: { backgroundColor: colors.background } }} />
        <Snackbar />
      </View>
      <ThemeFade target={screenRef} />
      <LockGate />
    </SafeAreaProvider>
  );
}
